#!/usr/bin/env python3
"""Block the "Generated with Claude Code" footer and session URLs from anything
that gets published: PR bodies, issues, comments, releases, commit messages.

The default harness instructions tell the model to append that footer to PR
bodies. This hook is what makes a repo's own rule win over that instruction,
since prose alone lost.

It also blocks a Claude co-author trailer: a Co-Authored-By line, with ":" or
"=" after the key, that carries an @anthropic.com address anywhere on that
line, case folded. EdSim's tools/loop_authorship.py applies the same address
test. A co-author trailer that names a person passes.

It also blocks the disclaimer line that the triage skill puts at the top of
each comment it posts ("generated by AI during triage").

Besides the command text, it reads the message file of a git or gh command
when the file is named after its own flag (-F path, --file, --body-file,
--notes-file, or flag=path) and the hook can find it. It reads the file as it
is before the command runs, so a file that the same command writes or changes
is not checked. This is a best-effort check. The guarantee for commits and PR
bodies is the CI scan (`scan`: the PR body, changed prose files and the PR's
commit messages), which does not scan issue comments or releases.

How it finds the file: it takes the path after the flag as written, either
absolute or relative to the folder it tracks. That folder starts at the
session folder and follows a plain `cd`, `git -C`, and a variable set earlier
in the same command. It does not split bundled short flags, so
`git commit -qF msg.txt` is not read.
"""
import importlib.util
import json
import os
import re
import shlex
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
try:
    import handrail_config
except Exception:  # a missing or broken config must not disarm the guard
    handrail_config = None


def _policy():
    """Effective policy, or None when it cannot be read.

    None means "enforce with no citation": a config that fails to load is a
    reason to keep guarding, never a reason to stop.
    """
    if handrail_config is None:
        return None
    try:
        return handrail_config.load()
    except Exception as exc:
        # The kind of failure, never the parser's message: that message quotes
        # the config back, and a TOML key is arbitrary text of unbounded length
        # reaching a block reason the model reads as an instruction.
        sys.stderr.write("handrail: config unreadable (%s), enforcing "
                         "defaults\n" % handrail_config.safe_error(exc))
        return None

BANNED = [
    (re.compile(r"Generated with \[?Claude Code", re.I), 'the "Generated with Claude Code" footer'),
    (re.compile(r"🤖\s*Generated with"), 'the robot-emoji generation footer'),
    (re.compile(r"https://claude\.ai/code/session_", re.I), "a claude.ai session URL"),
    # The triage skill opens every comment with this disclaimer (#37).
    (re.compile(r"generated\s+by\s+AI\s+during\s+triage", re.I),
     "the triage skill's AI disclaimer"),
    # Owner decision 2026-11-15 (#108): no Claude co-author. A co-author
    # trailer is Claude's when an @anthropic.com address is anywhere on the
    # trailer line, case folded. ":" or "=" may follow the key, after optional
    # space, since git commit --trailer takes both. A trailer that names a
    # person passes. A line that starts with a space or tab continues the
    # trailer, as git interpret-trailers reads it, so a folded address counts.
    (re.compile(r"Co-Authored-By\s*[:=](?:[^\n]|\n[ \t])*@anthropic\.com\b",
                re.I),
     "a Claude co-author trailer"),
]


# Flags through which git commit and gh (pr, issue, release) read a message or
# body from a file. "-" means stdin, which the command text already holds.
FILE_FLAGS = ("-F", "--file", "--body-file", "--notes-file")


VARIABLE = re.compile(r"\$(?:\{(\w+)\}|(\w+))")
OPERATOR = set("&|;()<>")


def _words(command):
    """Shell words of `command`, with ";" where a newline ends a command.

    A line whose quotes do not balance, e.g. an apostrophe in a heredoc, makes
    shlex fail on the whole text. Then each line is read alone and only the
    bad line is lost.
    """
    def lex(text):
        lexer = shlex.shlex(text.replace("\n", " ; "), posix=True,
                            punctuation_chars=True)
        lexer.whitespace_split = True
        lexer.commenters = ""  # a "#" in a body or an issue URL is no comment
        return list(lexer)
    try:
        return lex(command)
    except ValueError:
        words = []
        for line in command.split("\n"):
            try:
                words += lex(line) + [";"]
            except ValueError:
                pass
        return words


def _expand(word, shell_vars):
    """The word with $NAME and ${NAME} filled in: from an assignment earlier in
    the command first, then from the environment, then ~."""
    word = VARIABLE.sub(
        lambda m: shell_vars.get(m.group(1) or m.group(2), m.group(0)), word)
    return os.path.expanduser(os.path.expandvars(word))


def _review_hook():
    """require-code-review.py as a module, or None when it cannot load.

    That hook owns the reading of `cd` and of variable assignments, so both
    hooks read them the same way. A load can fail in any way, SystemExit
    included, and then the folder and the variables are unknown.
    """
    try:
        spec = importlib.util.spec_from_file_location(
            "require_code_review",
            Path(__file__).with_name("require-code-review.py"))
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        return module
    except BaseException:
        return None


def _read(name, cwd):
    """Text of the file `name`, or "" when it is stdin, unknown or absent."""
    path = Path(name)
    if not path.is_absolute():
        if cwd is None:
            return ""
        path = Path(cwd) / path
    try:
        if name != "-" and path.is_file():
            return path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        pass
    return ""


def _flag_files(words, cwd, review):
    """Text of the message files that the git or gh command in `words` reads."""
    start = next((i for i, w in enumerate(words)
                  if os.path.basename(w) in ("git", "gh")), None)
    if start is None:
        return []
    is_git = os.path.basename(words[start]) == "git"
    texts = []
    for i in range(start + 1, len(words)):
        tok = words[i]
        nxt = words[i + 1] if i + 1 < len(words) else None
        flag, eq, value = tok.partition("=")
        if is_git and tok == "-C" and nxt is not None:
            cwd = review._cd([nxt], cwd) if review else None
            continue
        if eq and flag in FILE_FLAGS:
            name = value
        elif tok in FILE_FLAGS and nxt is not None:
            name = nxt
        elif tok.startswith("-F") and len(tok) > 2:
            name = tok[2:]
        else:
            continue
        texts.append(_read(name, cwd))
    return texts


def _message_files(command, cwd):
    """Text of the files a git or gh command in `command` reads as a message.

    The Write tool can put a footer in msg.txt, and `git commit -F msg.txt`
    then carries nothing in its own text (#109). The walk follows `cd`,
    `git -C` and `NAME=value` assignments made earlier in the command. A file
    that does not exist yet, or sits in a folder the text does not settle, is
    skipped: the command text is still checked, and CI scans the commit
    messages git wrote.
    """
    review = _review_hook()
    if review is None:
        cwd = None
    texts, shell_vars, seg = [], {}, []
    for tok in _words(command) + [";"]:
        if not (tok and set(tok) <= OPERATOR):
            seg.append(tok)
            continue
        raw, seg = seg, []
        # Left to right, as the shell does: S=/a S2=$S/b gives S2 /a/b.
        for word in review.shell_assignments(raw) if review else ():
            key, eq, value = word.partition("=")
            if eq:
                shell_vars[key] = _expand(value, shell_vars)
        words = [_expand(w, shell_vars) for w in raw]
        while review and words and (words[0] in review.SHELL_PREFIXES
                                    or review.ASSIGNMENT.match(words[0])):
            words.pop(0)
        if review and words and words[0] in ("cd", "pushd"):
            cwd = review._cd(words[1:], cwd)
            continue
        texts += _flag_files(words, cwd, review)
    return "\n".join(texts)


def _banned(text):
    """The label of the first banned pattern in text, or None."""
    return next((label for pattern, label in BANNED if pattern.search(text)),
                None)


def _safe_path(value):
    # The fallback fires only when the module fails to import, which is a
    # degenerate state rather than an attack path. It still applies the same
    # substitution, because printing the raw path there would be the one
    # remaining way a directory name reaches a log as prose.
    if handrail_config:
        return handrail_config.safe_path(value)
    return re.sub(r"[^A-Za-z0-9._/-]", "?", str(value))


def _safe_error(exc):
    return (handrail_config.safe_error(exc) if handrail_config
            else type(exc).__name__)


def scan(paths):
    """CI mode: check files instead of a Bash command.

    The hook stops a publish at the moment it is typed. That only covers this
    laptop, so CI re-checks the artefacts themselves: the PR body, and any file
    in the diff.

    Returns the number of files with at least one finding.
    """
    bad = 0
    for name in paths:
        try:
            text = Path(name).read_text(encoding="utf-8", errors="replace")
        except OSError as exc:
            # Unreadable means unchecked, and unchecked must not read as clean.
            print("%s: cannot read (%s)" % (_safe_path(name),
                                            _safe_error(exc)), file=sys.stderr)
            bad += 1
            continue
        hits = [label for pattern, label in BANNED if pattern.search(text)]
        if hits:
            bad += 1
            for label in hits:
                print("%s: publishes %s" % (_safe_path(name), label),
                      file=sys.stderr)
    return bad


def main():
    # scan takes paths on argv. CI has no hook payload and must not block on a
    # stdin read that will never be fed.
    if len(sys.argv) > 1 and sys.argv[1] == "scan":
        sys.exit(1 if scan(sys.argv[2:]) else 0)

    try:
        payload = json.load(sys.stdin)
    except (json.JSONDecodeError, ValueError):
        sys.exit(0)

    # The cheap checks come first so a broken config warns on a Bash command
    # rather than on every tool call. This hook fires constantly, and a steady
    # warning is what teaches people to stop reading stderr.
    if payload.get("tool_name") != "Bash":
        sys.exit(0)
    command = payload.get("tool_input", {}).get("command", "")
    if not command:
        sys.exit(0)

    # The patterns are matched BEFORE the config is read. Resolving the policy
    # shells out to git, which costs about 11 ms, and this hook runs on every
    # Bash command while a command carrying a footer is rare. Checking the
    # switch here rather than up front is the same decision, paid for only when
    # it matters.
    # The command text is checked before any file is read, so a fault while
    # reading files can never switch off the check of the text itself.
    label = _banned(command) or _banned(
        _message_files(command, payload.get("cwd") or os.getcwd()))
    if label:
        policy = _policy()
        if policy is not None and not policy.enabled("ai_attribution"):
            sys.exit(0)
        citation = policy.citation() if policy else ""
        print(
            f"Blocked: this command would publish {label}.\n"
            "Never put AI-generation footers or session URLs in anything "
            "other people read: PR bodies, issues, comments, releases. "
            "Remove those lines and run it again.\n"
            "For the triage disclaimer, remove that one line and post "
            "the rest of the comment as it is.\n"
            "That covers a commit message too: a Claude-Session trailer "
            "is a session URL, and a co-author trailer at an "
            "anthropic.com address names Claude. A co-author trailer "
            "that names a person is fine."
            + (("\n" + citation) if citation else ""),
            file=sys.stderr,
        )
        sys.exit(2)
    sys.exit(0)


if __name__ == "__main__":
    main()
