#!/usr/bin/env python3
"""Self-test for no-ai-attribution.py. Run it after any edit to that hook.

Every case here exists because the hook once got it wrong, or because a check
that has never gone red proves nothing.
"""
import json
import subprocess
import sys
import tempfile
from pathlib import Path

HOOK = str(Path(__file__).with_name("no-ai-attribution.py"))
BLOCK, ALLOW = 2, 0

CASES = [
    ("PR body carrying the footer", BLOCK,
     'gh pr create --body "fix stuff\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)"'),
    ("PR body carrying a session URL", BLOCK,
     'gh pr create --body "fix stuff\n\nhttps://claude.ai/code/session_01ABC"'),
    ("issue comment carrying the footer", BLOCK,
     'gh issue comment 5 --body "done. Generated with Claude Code"'),
    ("release notes carrying the footer", BLOCK,
     'gh release create v1 --notes "🤖 Generated with Claude Code"'),
    # #109: a URL host is case-insensitive, so the pattern must be too.
    ("PR body carrying a session URL with an uppercase host", BLOCK,
     'gh pr create --body "fix stuff\n\nhttps://Claude.ai/code/session_01ABC"'),
    ("heredoc PR body carrying a session URL", BLOCK,
     'gh pr create --body-file - <<EOF\nwork\n\nhttps://claude.ai/code/session_01XYZ\nEOF'),
    # Owner decision 2026-11-15 (#35): the session trailer carries a session
    # URL, so it blocks like any other.
    ("commit message with only the trailers", BLOCK,
     'git commit -m "fix: thing\n\nCo-Authored-By: Claude Opus 5 <noreply@anthropic.com>\n'
     'Claude-Session: https://claude.ai/code/session_01ABC"'),
    # Owner decision 2026-11-15 (#108): no more Claude co-author. The match is
    # on the address, case folded, as EdSim's tools/loop_authorship.py does.
    ("commit message with only a Claude co-author trailer", BLOCK,
     'git commit -m "fix: thing\n\nCo-Authored-By: Claude <noreply@anthropic.com>"'),
    ("a Claude co-author trailer in another case", BLOCK,
     'git commit -m "fix: thing\n\nco-authored-by: Claude Opus 5 <NoReply@Anthropic.COM>"'),
    ("a co-author trailer that names a person", ALLOW,
     'git commit -m "fix: thing\n\nCo-Authored-By: Ada Lovelace <ada@example.org>"'),
    # git also takes "=" as the separator in --trailer, and writes the
    # trailer with a colon. A space before the separator is legal too.
    ("a Claude co-author trailer with = as the separator", BLOCK,
     'git commit -m fix --trailer "Co-authored-by=Claude <noreply@anthropic.com>"'),
    ("a Claude co-author trailer with a space before the colon", BLOCK,
     'git commit -m "fix: thing\n\nCo-Authored-By : Claude <noreply@anthropic.com>"'),
    # The trailer can sit in the middle of a command line, after no newline.
    ("a Claude co-author trailer passed with --trailer", BLOCK,
     'git commit -m fix --trailer "Co-Authored-By: Claude <noreply@anthropic.com>"'),
    ("a Claude co-author trailer passed as a second -m", BLOCK,
     'git commit -m fix -m "Co-Authored-By: Claude <noreply@anthropic.com>"'),
    # The address must be on the trailer line, not anywhere later.
    ("a person co-author and an anthropic.com address on another line", ALLOW,
     'git commit -m "fix: thing\n\nCo-Authored-By: Jane <jane@example.com>\n'
     'see noreply@anthropic.com docs"'),
    # #37: the triage skill opens every comment with an AI disclaimer. The
    # owner decided to block that line and leave the rest of triage as it is.
    ("triage comment carrying the AI disclaimer", BLOCK,
     'gh issue comment 5 --body "> *This was generated by AI during triage.*\n\nLooks like a bug."'),
    ("triage issue carrying the AI disclaimer", BLOCK,
     'gh issue create --title t --body "> *This was generated by AI during triage.*\n\nSteps below."'),
    ("the disclaimer in another case and with no markdown", BLOCK,
     'gh issue comment 5 --body "This was Generated by AI during triage"'),
    # #109: these four cases kill the loose patterns that survived the #37
    # review: single spaces for \s+, "AI during triage" alone, a required
    # "This was" prefix, and \w*AI\w*.
    ("the disclaimer with no prefix and runs of whitespace", BLOCK,
     'gh issue comment 5 --body "Generated  by\nAI   during triage."'),
    ("AI during triage in ordinary text", ALLOW,
     'gh issue comment 5 --body "we used AI during triage to sort labels"'),
    ("a word that holds the letters ai, during triage", ALLOW,
     'gh issue comment 5 --body "the report was generated by email during triage"'),
    ("triage text that names AI tooling", ALLOW,
     'gh issue comment 5 --body "triage this issue, it was flagged by AI tooling"'),
    ("the word generated in ordinary text", ALLOW,
     'gh pr create --body "the lockfile is generated by npm"'),
    ("a triage comment with the disclaimer removed", ALLOW,
     'gh issue comment 5 --body "Looks like a bug. Steps to reproduce below."'),
    ("ordinary PR", ALLOW, 'gh pr create --body "a normal body"'),
    ("a PR that merely mentions the product by name", ALLOW,
     'gh pr create --body "adds a Claude Code hook"'),
]


# #109: text a git or gh command reads from a file. Each case is (name, want,
# file text, command). The file is written as "msg.txt" in a temp folder that
# is the payload's cwd, the way the Write tool leaves it for the next command.
FILE_CASES = [
    ("git commit -F with a session trailer in the file", BLOCK,
     "fix: x\n\nClaude-Session: https://claude.ai/code/session_01ABC\n",
     "git commit -F msg.txt"),
    ("git commit --file= with a Claude co-author trailer in the file", BLOCK,
     "fix: x\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n",
     "git add -A && git commit --file=msg.txt"),
    ("gh pr create --body-file with the footer in the file", BLOCK,
     "work\n\nGenerated with [Claude Code](https://claude.com/claude-code)\n",
     "gh pr create --title t --body-file msg.txt"),
    ("gh issue comment --body-file with the triage disclaimer", BLOCK,
     "> *This was generated by AI during triage.*\n\nLooks like a bug.\n",
     "gh issue comment 5 --body-file msg.txt"),
    ("gh issue create -F with the triage disclaimer", BLOCK,
     "> *This was generated by AI during triage.*\n\nSteps below.\n",
     "gh issue create --title t -F msg.txt"),
    ("gh release create --notes-file with the footer", BLOCK,
     "notes\n\nGenerated with Claude Code\n",
     "gh release create v1 --notes-file msg.txt"),
    ("git commit -F with a clean message", ALLOW,
     "fix: x\n\nCo-Authored-By: Ada Lovelace <ada@example.org>\n",
     "git commit -F msg.txt"),
    # Only a git or gh command reads the file as a message. tail -F follows a
    # log, and a log may quote the banned text.
    ("tail -F on a file that holds the footer", ALLOW,
     "Generated with Claude Code\n", "tail -F msg.txt"),
    # The file may not exist yet. The command text is all there is to check.
    ("git commit -F on a file that does not exist", ALLOW,
     "", "git commit -F missing.txt"),
]


def run(payload, stderr=False):
    done = subprocess.run([sys.executable, HOOK], input=payload,
                          capture_output=True, text=True)
    return done.stderr if stderr else done.returncode


def main():
    failures = 0
    for name, want, command in CASES:
        got = run(json.dumps({"tool_name": "Bash", "tool_input": {"command": command}}))
        if got != want:
            failures += 1
            print(f"FAIL want={want} got={got}  {name}")
    for name, want, text, command in FILE_CASES:
        with tempfile.TemporaryDirectory() as tmp:
            Path(tmp, "msg.txt").write_text(text, encoding="utf-8")
            got = run(json.dumps({"tool_name": "Bash", "cwd": tmp,
                                  "tool_input": {"command": command}}))
        if got != want:
            failures += 1
            print(f"FAIL want={want} got={got}  {name}")
    for name, payload in (("non-Bash tool", json.dumps({"tool_name": "Read", "tool_input": {}})),
                          ("empty stdin", ""),
                          ("malformed stdin", "{not json")):
        got = run(payload)
        if got != ALLOW:
            failures += 1
            print(f"FAIL want={ALLOW} got={got}  {name}")

    # A block that does not say what to do sends the agent into retries.
    triage = CASES[[c[0] for c in CASES].index(
        "triage comment carrying the AI disclaimer")][2]
    said = run(json.dumps({"tool_name": "Bash", "tool_input": {"command": triage}}),
               stderr=True)
    if "post the rest" not in said:
        failures += 1
        print("FAIL the triage block message does not say to post the rest")

    print("no-ai-attribution: all checks pass" if not failures
          else f"no-ai-attribution: {failures} FAILED")
    sys.exit(1 if failures else 0)


if __name__ == "__main__":
    main()
